# ---------------------------------------------------------------------------
# Pipeline profiles: typical operating values for each pipeline type.
# These are generic demonstration values, not design values.
# ---------------------------------------------------------------------------
@dataclass(frozen=True)
class PipelineProfile:
    name: str
    nominal_pressure_kpa: float  # pressure at the inlet station
    pressure_drop_per_km: float  # simple linear friction loss
    nominal_flow: float
    flow_unit: str
    nominal_temperature_c: float


