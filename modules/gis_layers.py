def read_uploaded_layer(filename: str, content: bytes) -> tuple[gpd.GeoDataFrame, list[str]]:
    """Read GeoJSON, GeoPackage or zipped Shapefile bytes. Returns (data in EPSG:4326, warnings)."""
    warnings = []
    suffix = Path(filename).suffix.lower()
    if suffix not in {".geojson", ".json", ".gpkg", ".zip"}:
        raise ValueError("Supported formats: .geojson / .json, .gpkg, or a .zip containing a Shapefile.")
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / f"upload{suffix}"
        path.write_bytes(content)
        gdf = gpd.read_file(path)
    if gdf.empty:
        raise ValueError("The file contains no features.")
    if gdf.crs is None:
        warnings.append("The file has no coordinate system; assumed WGS84 latitude/longitude (EPSG:4326).")
        gdf = gdf.set_crs(4326)
    gdf = gdf[gdf.geometry.notna() & ~gdf.geometry.is_empty]
    return gdf.to_crs(4326), warnings


def prepare_user_layer(gdf_4326: gpd.GeoDataFrame, category: str, frame: CorridorFrame,
                       name: str, source: str) -> tuple[gpd.GeoDataFrame, list[str]]:
    """Keep allowed geometry types, project to the corridor CRS and clip to the study area."""
    warnings = []
    allowed = CATEGORIES[category]["geom"]
    keep = gdf_4326.geometry.geom_type.isin(allowed)
    if (~keep).any():
        warnings.append(f"{int((~keep).sum())} feature(s) with geometry types not used for "
                        f"'{CATEGORIES[category]['label']}' were ignored.")
    gdf = gdf_4326[keep].to_crs(frame.crs_epsg)
    gdf = gdf.assign(geometry=gdf.geometry.make_valid().intersection(frame.study_area()))
    gdf = gdf[~gdf.geometry.is_empty]
    if gdf.empty:
        warnings.append("No features fall inside this project's study area.")
    if "name" in gdf.columns:
        names = [str(n) if pd.notna(n) else f"{name} #{i + 1}" for i, n in enumerate(gdf["name"])]
    else:
        names = [f"{name} #{i + 1}" for i in range(len(gdf))]
    out = gpd.GeoDataFrame({"name": names, "category": category, "source": source, "synthetic": False},
                           geometry=list(gdf.geometry), crs=frame.crs_epsg)
    return out, warnings


def assemble_layers(frame: CorridorFrame, user_layers: list[dict]) -> tuple[dict[str, gpd.GeoDataFrame], list[dict]]:
    """Combine user layers (where supplied) with synthetic layers (everywhere else).

    `user_layers` are rows from `projects.list_layers` (with GeoJSON text).
    Returns the layers by category and a data-source register for display.
    """
    synthetic = synthetic_layers(frame)
    layers, register = {}, []
    for cat, info in CATEGORIES.items():
        mine = [r for r in user_layers if r["category"] == cat]
        if mine:
            parts = []
            for r in mine:
                gdf, _ = prepare_user_layer(gpd.read_file(r["geojson"]), cat, frame, r["name"], r["source"])
                parts.append(gdf)
                register.append({"category": info["label"], "layer": r["name"], "source": r["source"],
                                 "licence": r.get("licence") or "", "features": len(gdf), "data_type": "User-supplied",
                                 "confidence": "Unverified coverage: check completeness",
                                 "notes": r.get("notes") or ""})
            layers[cat] = gpd.GeoDataFrame(pd.concat(parts, ignore_index=True), crs=frame.crs_epsg)
        elif cat in NO_SYNTHETIC:
            layers[cat] = synthetic[cat]
            register.append({"category": info["label"], "layer": "None", "source": "n/a", "licence": "n/a",
                             "features": 0, "data_type": "Not available", "confidence": "Not assessed: data gap",
                             "notes": "No synthetic substitute is generated. Impacts are unknown, not absent. "
                                      "Upload authorised data to assess."})
        else:
            layers[cat] = synthetic[cat]
            register.append({"category": info["label"], "layer": f"Synthetic {info['label'].lower()}",
                             "source": SYNTHETIC_SOURCE, "licence": "n/a", "features": len(synthetic[cat]),
                             "data_type": "Synthetic demonstration", "confidence": "None: not real data",
                             "notes": "Replace by uploading real data for this category."})
    return layers, register

