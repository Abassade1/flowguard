# Synthetic terrain
# ---------------------------------------------------------------------------
def synthetic_elevation(frame: CorridorFrame, x, y) -> np.ndarray:
    """SYNTHETIC elevation (m): a ridge crossing the direct line, and a valley along a river."""
    L = frame.length_m
    u, v = frame.to_uv(x, y)
    un, vn = u / L, v / L
    ridge = 320 * np.exp(-(((un - 0.42) / 0.025) ** 2)) * np.exp(-(((vn + 0.02) / 0.20) ** 2))
    valley = -70 * np.exp(-(((vn - 0.20) / 0.06) ** 2))
    rolling = 25 * np.sin(un * 9.0) * np.cos(vn * 7.0)
    return 650 + 60 * un + ridge + valley + rolling


# ---------------------------------------------------------------------------
# Synthetic constraint layers
# ---------------------------------------------------------------------------
def _ellipse(frame, uc, vc, au, av, n=48):
    L = frame.length_m
    t = np.linspace(0, 2 * np.pi, n, endpoint=False)
    return Polygon(zip(*frame.to_xy((uc + au * np.cos(t)) * L, (vc + av * np.sin(t)) * L)))


def _line(frame, u_frac, v_frac):
    L = frame.length_m
    return LineString(zip(*frame.to_xy(np.asarray(u_frac) * L, np.asarray(v_frac) * L)))


def synthetic_layers(frame: CorridorFrame) -> dict[str, gpd.GeoDataFrame]:
    """Clearly labelled demonstration features arranged to create real trade-offs."""
    t = np.linspace(0, 1, 60)
    s = np.linspace(-0.45, 0.45, 60)
    features = {
        "water": [
            ("SYNTHETIC river R-1", _line(frame, 0.22 + 0.03 * np.sin(s * 12), s)),
            ("SYNTHETIC river R-2", _line(frame, 0.58 + 0.04 * np.sin(s * 9 + 1), s)),
            ("SYNTHETIC creek R-3", _line(frame, 0.80 + 0.02 * np.sin(s * 15), np.linspace(-0.45, 0.20, 60))),
            ("SYNTHETIC valley river R-4", _line(frame, np.linspace(0.05, 1.05, 60),
                                                 0.20 + 0.03 * np.sin(np.linspace(0, 14, 60)))),
        ],
        "wetland": [
            ("SYNTHETIC wetland W-1", _ellipse(frame, 0.66, 0.02, 0.05, 0.07)),
            ("SYNTHETIC wetland W-2", _ellipse(frame, 0.35, 0.21, 0.08, 0.03)),
            ("SYNTHETIC wetland W-3", _ellipse(frame, 0.85, 0.19, 0.06, 0.03)),
            ("SYNTHETIC wetland W-4", _ellipse(frame, 0.20, -0.18, 0.03, 0.04)),
        ],
        "forest": [
            ("SYNTHETIC forest F-1", _ellipse(frame, 0.50, -0.27, 0.40, 0.12)),
            ("SYNTHETIC forest F-2", _ellipse(frame, 0.15, 0.06, 0.07, 0.08)),
        ],
        "protected": [
            ("SYNTHETIC protected area PA-1", _ellipse(frame, 0.45, 0.0, 0.06, 0.10)),
        ],
        "road": [
            # An arch that leaves the start, swings ~30% of the distance to one side, and returns.
            ("SYNTHETIC highway / utility corridor H-1", _line(frame, t, 0.30 * np.sin(np.pi * t) ** 0.4)),
        ],
    }
    features.update({cat: [] for cat in NO_SYNTHETIC})
    area = frame.study_area()
    out = {}
    for cat, items in features.items():
        gdf = gpd.GeoDataFrame(
            {"name": [n for n, _ in items], "category": cat, "source": SYNTHETIC_SOURCE, "synthetic": True},
            geometry=[g for _, g in items], crs=frame.crs_epsg,
        )
        gdf["geometry"] = gdf.geometry.intersection(area)
        out[cat] = gdf[~gdf.geometry.is_empty].reset_index(drop=True)
    return out


