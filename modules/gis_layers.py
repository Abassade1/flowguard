"""GIS layers for route planning: coordinate frames, synthetic layers and user uploads.

Key ideas:

* All geometry calculations happen in a projected CRS (UTM, metres) chosen from
  the project's location, so lengths and areas are real distances.
  Maps are drawn in latitude/longitude (EPSG:4326).
* Constraint categories: water, wetland, forest, protected, road (existing corridor).
* If the user has not supplied data for a category, a SYNTHETIC demonstration
  layer is generated around the start-destination corridor (except habitat,
  which is left as an explicit data gap). Synthetic features
  are labelled as such everywhere and must never be read as real geography.
* User-supplied layers replace the synthetic layer for their category, and each
  carries a source record (provider, licence, notes) for data-source tracking.
"""

import tempfile
from dataclasses import dataclass
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
from pyproj import CRS, Transformer
from shapely.geometry import LineString, Polygon

from modules.projects import Project

CATEGORIES: dict[str, dict] = {
    "water": {"label": "Rivers & lakes", "geom": ("LineString", "MultiLineString", "Polygon", "MultiPolygon")},
    "wetland": {"label": "Wetlands", "geom": ("Polygon", "MultiPolygon")},
    "forest": {"label": "Forest cover", "geom": ("Polygon", "MultiPolygon")},
    "protected": {"label": "Protected areas (hard constraint)", "geom": ("Polygon", "MultiPolygon")},
    "road": {"label": "Existing roads / utility corridors", "geom": ("LineString", "MultiLineString")},
    "habitat": {"label": "Sensitive wildlife habitat", "geom": ("Polygon", "MultiPolygon")},
}

# Categories with no synthetic stand-in: inventing wildlife habitat (even as a demo) would hide
# the fact that it is unknown. Without user data these show as a data gap.
NO_SYNTHETIC = {"habitat"}

SYNTHETIC_SOURCE = "SYNTHETIC: generated by FlowGuard (not real)"


def utm_crs_for(lon: float, lat: float) -> CRS:
    """The UTM zone CRS (metres) that contains a point."""
    zone = int((lon + 180) // 6) + 1
    return CRS.from_epsg((32600 if lat >= 0 else 32700) + zone)


@dataclass(frozen=True)
class CorridorFrame:
    """A local frame aligned with the straight line from start to destination.

    u = metres along the start→destination axis, v = metres to the left of it.
    Synthetic features are designed in (u, v) and converted to projected x/y.
    """

    crs_epsg: int
    x0: float
    y0: float
    x1: float
    y1: float

    @property
    def length_m(self) -> float:
        return float(np.hypot(self.x1 - self.x0, self.y1 - self.y0))

    @property
    def axes(self) -> tuple[np.ndarray, np.ndarray]:
        eu = np.array([self.x1 - self.x0, self.y1 - self.y0]) / self.length_m
        ev = np.array([-eu[1], eu[0]])
        return eu, ev

    def to_xy(self, u, v):
        eu, ev = self.axes
        u, v = np.asarray(u, float), np.asarray(v, float)
        return self.x0 + u * eu[0] + v * ev[0], self.y0 + u * eu[1] + v * ev[1]

    def to_uv(self, x, y):
        eu, ev = self.axes
        dx, dy = np.asarray(x, float) - self.x0, np.asarray(y, float) - self.y0
        return dx * eu[0] + dy * eu[1], dx * ev[0] + dy * ev[1]

    def study_area(self) -> Polygon:
        """Rotated rectangle around the corridor: 15% beyond each end, ±45% to each side."""
        L = self.length_m
        u = np.array([-0.15, 1.15, 1.15, -0.15]) * L
        v = np.array([-0.45, -0.45, 0.45, 0.45]) * L
        return Polygon(zip(*self.to_xy(u, v)))


def corridor_frame(project: Project) -> CorridorFrame:
    crs = utm_crs_for((project.start_lon + project.end_lon) / 2, (project.start_lat + project.end_lat) / 2)
    to_utm = Transformer.from_crs(4326, crs, always_xy=True)
    x0, y0 = to_utm.transform(project.start_lon, project.start_lat)
    x1, y1 = to_utm.transform(project.end_lon, project.end_lat)
    return CorridorFrame(crs.to_epsg(), x0, y0, x1, y1)


